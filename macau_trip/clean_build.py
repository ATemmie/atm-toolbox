def build_clean_doc():
    doc = Document()

    # A4 page
    section = doc.sections[0]
    section.page_width = Cm(21)
    section.page_height = Cm(29.7)
    section.top_margin = Cm(2.5)
    section.bottom_margin = Cm(2.5)
    section.left_margin = Cm(2.5)
    section.right_margin = Cm(2.5)

    # 封面
    for _ in range(8):
        doc.add_paragraph()

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run("澳门家庭旅行执行表")
    run.font.size = Pt(26)
    run.font.bold = True

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = subtitle.add_run("6人家庭 · 2天1夜 · 威尼斯人出发\n2026年8月23-25日")
    run.font.size = Pt(12)

    doc.add_page_break()

    # 简洁目录
    h = doc.add_heading("目录", level=1)
    toc_items = [
        "1. 总体思路：两天分成两个区域",
        "2. 23号晚上：抵达+入住",
        "3. 24号：澳门半岛一条线",
        "4. 25号：氹仔+路氹",
        "5. 天气备用路线",
        "6. 交通优先级",
        "7. 核心景点TOP 10",
        "8. 原始规划细节（完整文本）",
    ]
    for item in toc_items:
        p = doc.add_paragraph(item)
        for run in p.runs:
            run.font.size = Pt(11)

    doc.add_page_break()

    # 把原文按段落写入，保持原始格式
    # 简单处理：按行写入，遇到#开头的做heading
    lines = ORIGINAL_TEXT.split('\n')
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()

        # 空行
        if not line:
            doc.add_paragraph()
            i += 1
            continue

        # 分隔线
        if line.strip() in ['---', '***', '___']:
            # 不加page break，只加个空行
            doc.add_paragraph()
            i += 1
            continue

        # Headings
        if line.startswith('# '):
            text = line.lstrip('# ').strip()
            # 去掉emoji
            clean = ''.join(c for c in text if ord(c) < 0x1F600 or ord(c) > 0x1FFFF)
            doc.add_heading(clean if clean else text, level=1)
            i += 1
            continue
        if line.startswith('## '):
            text = line.lstrip('# ').strip()
            doc.add_heading(text, level=2)
            i += 1
            continue
        if line.startswith('### '):
            text = line.lstrip('# ').strip()
            doc.add_heading(text, level=3)
            i += 1
            continue

        # Blockquote
        if line.startswith('> '):
            text = line[2:].strip()
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Cm(1)
            run = p.add_run(text)
            run.font.italic = True
            run.font.color.rgb = RGBColor(100, 100, 100)
            i += 1
            continue

        # Table (markdown)
        if '|' in line and line.strip().startswith('|'):
            # 收集整个表格
            table_lines = []
            while i < len(lines) and '|' in lines[i] and lines[i].strip().startswith('|'):
                tl = lines[i].strip()
                # 跳过分隔行 |----|
                if all(c in '|-: ' for c in tl):
                    i += 1
                    continue
                cells = [c.strip() for c in tl.split('|')[1:-1]]
                table_lines.append(cells)
                i += 1
            if table_lines:
                cols = max(len(r) for r in table_lines)
                table = doc.add_table(rows=len(table_lines), cols=cols)
                for ri, row_data in enumerate(table_lines):
                    for ci, cell_text in enumerate(row_data):
                        if ci < cols:
                            table.cell(ri, ci).text = cell_text
            continue

        # List items
        if line.strip().startswith('- ') or line.strip().startswith('* '):
            text = line.strip()[2:].strip()
            # 去掉markdown bold
            text = text.replace('**', '')
            p = doc.add_paragraph(text, style='List Bullet')
            i += 1
            continue

        # Numbered list
        import re
        m = re.match(r'^(\d+)\.\s+(.+)', line.strip())
        if m:
            text = m.group(2).strip().replace('**', '')
            p = doc.add_paragraph(text, style='List Number')
            i += 1
            continue

        # Regular paragraph
        text = line.strip().replace('**', '')
        # Clean emoji-heavy prefixes but keep content
        p = doc.add_paragraph(text)
        for run in p.runs:
            run.font.size = Pt(11)
        i += 1

    doc.save(str(FINAL_DOC))
    print(f"✅ 已保存: {FINAL_DOC}")
    print(f"   大小: {FINAL_DOC.stat().st_size // 1024}KB")

